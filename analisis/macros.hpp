// ----------------------------------------------------------------------------
// FOR - цикл со счетчиком
// ----------------------------------------------------------------------------
// Использование: FOR(начало, конец, тело_цикла)
//
// Параметры:
//   start - начальное значение (включительно)
//   end   - конечное значение (не включительно)
//   body  - тело цикла
//
// Особенности:
//   - Переменная i доступна в теле цикла
//   - Переменная stop для управления выходом
//   - Автоматический подсчет итераций
//   - Поддерживает BREAK
//
// Пример:
//   FOR(0, 10, {
//       if (i == 5) BREAK;
//       std::cout << i << " ";
//   })
//   Вывод: 0 1 2 3 4
// ----------------------------------------------------------------------------

#define FOR(start, end, body) \
    FORCounter::forLoop(start, end, [&](auto i, auto& stop) { body; })


// ----------------------------------------------------------------------------
// WHILE - цикл с условием
// ----------------------------------------------------------------------------
// Использование: WHILE(начало, условие, тело_цикла)
//
// Параметры:
//   start     - начальное значение счетчика
//   condition - условие продолжения (лямбда с 1 параметром)
//   body      - тело цикла
//
// Особенности:
//   - Переменная i доступна в теле цикла и условии
//   - Переменная stop для управления выходом
//   - Автоматический подсчет итераций
//   - Поддерживает BREAK
//
// Пример:
//   WHILE(0, [&](int i) { return i < 10; }, {
//       if (i == 5) BREAK;
//       std::cout << i << " ";
//   })
//   Вывод: 0 1 2 3 4
// ----------------------------------------------------------------------------

#define WHILE(start, condition, body) \
    WhileCounter::whileLoop(start, condition, [&](auto i, auto& stop) { body; })


// ----------------------------------------------------------------------------
// BREAK - досрочный выход из цикла
// ----------------------------------------------------------------------------
// Использование: BREAK;
//
// Описание:
//   Обеспечивает досрочный выход из текущего цикла (FOR или WHILE).
//   Аналог оператора break.
//
// Пример:
//   FOR(0, 100, {
//       if (i == 5) {
//           BREAK;  // Выход при i == 5
//       }
//   })
// ----------------------------------------------------------------------------

#define BREAK stop = true